"""Generate frontend/src/cities/detroit/vocab.generated.ts from the Detroit static data.

PURPOSE
    The Detroit frontend vocabularies (zone codes, transit colours, railroad owner marks,
    POI category counts) must match what the static build actually exported — not what
    someone remembers. This reads the same cached importer output the static build used
    (no network if the cache is warm) and writes plain data constants. Hand-written
    labels/colours live in taxonomies.ts / zoning.ts; their tests check they cover every
    value generated here.

USAGE (from backend/, after export_city_static has run):
    .venv-build/bin/python -m app.data_import.detroit.frontend_vocab

FLOW
    main() → layer_rows() per (layer id, tile layer) → summarise → render_ts() → write
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import yaml

from app.data_import.detroit.static_plan import STATIC_PLAN
from app.data_import.static_build import importer_config

BACKEND_DIR = Path(__file__).resolve().parents[3]
CONFIG = BACKEND_DIR / "app" / "data_import" / "configs" / "detroit.yaml"
OUT = BACKEND_DIR.parent / "frontend" / "src" / "cities" / "detroit" / "vocab.generated.ts"


def layer_rows(sources: dict, layer_id: str, tile_name: str) -> list[dict]:
    """O(n) time, O(n) space — n = rows the tile layer's importer produces (cached input)."""
    # O(T) time, O(T) space — T = tile layers across the plan (≈ 16)
    tiles = {(s.layer_id, t.name): t for s in STATIC_PLAN.layers for t in s.tile_layers}
    tile = tiles.get((layer_id, tile_name))
    if tile is not None:
        importer = tile.importer(
            db_url="", city_id=STATIC_PLAN.slug,
            config=importer_config(sources, tile.config_keys),
        )
        return tile.select(importer.transform(importer.download()))
    raise KeyError(f"{layer_id}/{tile_name} not in STATIC_PLAN")


def unambiguous_colors(lines: list[dict]) -> dict[str, str]:
    """O(n log n) time, O(n) space — n = transit lines (sorted for a stable file).

    line_name → colour, leaving out names two systems share with DIFFERENT colours
    (DDOT and SMART both run "Greenfield", "Grand River", "Jefferson", "Southfield").
    The shared TransitLayer falls back to each feature's own `color`, so those lines still
    draw in their GTFS colour; a single map entry would paint one system's line wrong.
    """
    seen: dict[str, set[str]] = {}
    # O(n) time, O(n) space — n = lines
    for line in lines:
        if line.get("line_name") and line.get("color"):
            seen.setdefault(line["line_name"], set()).add(line["color"].upper())
    # O(n log n) time, O(n) space — n = distinct names (sorted)
    return {name: next(iter(c)) for name, c in sorted(seen.items()) if len(c) == 1}


def render_ts(vocab: dict) -> str:
    """O(s) time, O(s) space — s = size of the vocab JSON."""
    header = (
        "/**\n"
        " * GENERATED by backend/app/data_import/detroit/frontend_vocab.py from the Detroit\n"
        " * static build. Do not edit by hand — re-run the generator after a rebuild.\n"
        " * O(1) time, O(1) space — c = constant data.\n"
        " */\n"
    )
    # O(k) time, O(s) space — k = constants (5); s = their serialised size
    body = "".join(
        f"export const {name} = {json.dumps(value, indent=2, sort_keys=True)} as const;\n\n"
        for name, value in vocab.items()
    )
    return header + body


def main() -> int:
    """O(N log N) time, O(N) space — N = rows across the summarised layers."""
    sources = yaml.safe_load(CONFIG.read_text())["sources"]
    zoning = layer_rows(sources, "zoning", "zoning_districts")
    lines = layer_rows(sources, "transit", "transit_lines")
    railroads = layer_rows(sources, "railroads", "railroads")
    pois = layer_rows(sources, "pois", "pois")
    # O(n) time, O(k) space — n = rows; k = distinct values (each Counter below)
    zone_counts = Counter(z["zone_code"] for z in zoning if z.get("zone_code"))
    vocab = {
        "DETROIT_EXPORTED_ZONE_CODES": dict(sorted(zone_counts.items())),
        "DETROIT_GTFS_LINE_COLORS": unambiguous_colors(lines),
        # O(n) time, O(k) space — n = railroad ways; k = owner marks
        "DETROIT_RAILROAD_OWNER_COUNTS": dict(Counter(r["owner"] for r in railroads)),
        # O(n) time, O(k) space — n = railroad ways; k = ownership types
        "DETROIT_RAILROAD_OWNER_TYPE_COUNTS": dict(Counter(r["owner_type"] for r in railroads)),
        # O(n) time, O(k) space — n = POIs; k = categories
        "DETROIT_POI_COUNTS": dict(Counter(p["category"] for p in pois)),
    }
    OUT.write_text(render_ts(vocab))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
