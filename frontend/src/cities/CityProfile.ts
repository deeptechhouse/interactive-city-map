/**
 * CityProfile — everything that differs between cities, in one typed object.
 *
 * PURPOSE
 *   Today city differences are scattered `if (citySlug === 'chicago')` branches
 *   (useMapLayers.ts, App.tsx, ContactResolver.ts, useContactList.ts) plus Chicago-only
 *   constants (CTA_LINE_COLORS, zoningTypes.ZONE_CLASSES, RailroadFilter owners,
 *   CHICAGO_BOUNDARIES). This port collects them so a city is *added* (a new profile
 *   file) rather than *edited into* shared code. See docs/detroit_parity/detroit_tdd.html §3.
 *
 * STATUS — SKELETON (2026-10-02). Nothing imports this file yet, so it cannot change
 *   Chicago behaviour. Wiring happens in plan Phase 4 (registry seam), after Chicago's
 *   current layer list is pinned by a snapshot test.
 *
 * ARCHITECTURE
 *   CityProfile (port) ← chicago/ and detroit/ (adapters) ← registry.ts (lookup by slug).
 *   Shared code asks the profile; it never asks "which city is this?".
 *
 * TO ADD A CITY: create src/cities/<slug>/index.ts exporting a CityProfile and add one
 *   line to registry.ts. No other shared file should need a city branch.
 */
import type { LayerState } from '../types/layer';
import type { ZoneClass } from '../utils/zoningTypes';
import type { BoundaryIndex, FocusKind } from '../focus/focusGeometry';
import type { AreaOption } from '../focus/focusAreas';
import type { BusinessSource, OwnerSource } from '../contacts/publicRecords';

/** One entry in a legend/filter list (railroad owners, ownership types, transit systems). */
export interface TaxonomyEntry {
  readonly key: string;
  readonly label: string;
  readonly color: string;
}

/** Static-mode assets — paths are relative to the Vite `public/` root. */
export interface StaticAssets {
  /** Protomaps basemap clipped to the city (e.g. `./data/detroit/basemap.pmtiles`). */
  readonly basemapPmtiles: string;
  /** layer id → `pmtiles://…` URL, or '' when the layer uses bundled GeoJSON instead. */
  readonly layerPmtiles: Readonly<Record<string, string>>;
}

/** Focus-area config: which boundary sets the Focus panel offers and what they are called. */
export interface FocusConfig {
  /** Lazy so a city's boundary GeoJSON is only parsed when that city is selected. */
  loadBoundaries(): Promise<BoundaryIndex>;
  readonly optionsFor: (index: BoundaryIndex) => Record<FocusKind, readonly AreaOption[]>;
  readonly kindLabels: Readonly<Record<FocusKind, string>>;
}

/** Contact-list public-record sources (browser-side, free, keyless). */
export interface ContactSources {
  readonly owners: OwnerSource;
  readonly businesses: BusinessSource;
  /** Postal defaults for CSV rows and Tracerfy batches ("DETROIT", "MI"). */
  readonly postalCity: string;
  readonly postalState: string;
  /** State corporation-registry search link (IL SOS for Chicago, MI LARA for Detroit). */
  readonly corporationSearchUrl: (entityName: string) => string;
}

/** Click-popup HTML builders for layers the shared MapContainer does not know about. */
export type PopupBuilder = (properties: Readonly<Record<string, unknown>>) => string;

export interface CityProfile {
  readonly slug: string;
  readonly name: string;
  readonly state: string;
  readonly county: string;
  readonly center: readonly [number, number];
  readonly defaultZoom: number;
  readonly bounds: readonly [[number, number], [number, number]];

  /** Ordered layer list shown in LayerPanel — replaces createDefaultLayers' city branches. */
  layers(): LayerState[];
  /** Dev-mode (Martin) tile URL per layer id; '' = layer has no tile source in this mode. */
  devSources(): Readonly<Record<string, string>>;
  readonly staticAssets: StaticAssets;

  /** Layer ids with a click popup in this city, mapped to their builder. */
  readonly popups: Readonly<Record<string, PopupBuilder>>;

  readonly zoning: readonly ZoneClass[];
  readonly railroadOwners: readonly TaxonomyEntry[];
  readonly railroadOwnershipTypes: readonly TaxonomyEntry[];
  /** Transit line colour by `line_name` (or `system` fallback). */
  readonly transitColors: Readonly<Record<string, string>>;
  /** POI category → count, for the filter badges (generated by the static exporter). */
  readonly poiCategoryCounts: Readonly<Record<string, number>>;

  /** null = feature not offered in this city (panel shows a clear note). */
  readonly focus: FocusConfig | null;
  readonly contacts: ContactSources | null;
}

/**
 * Shared stub body for skeleton functions. Takes the arguments so `noUnusedParameters`
 * stays green without renaming the TDD's parameter names. Delete once nothing calls it.
 * O(1) time, O(1) space.
 */
export function notImplemented(what: string, ...args: unknown[]): never {
  throw new Error(`[skeleton] ${what}(${args.length} args) is not implemented yet — see docs/detroit_parity/`);
}
