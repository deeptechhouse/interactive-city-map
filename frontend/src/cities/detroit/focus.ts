/**
 * Detroit focus areas — zip codes, DPD precincts, council districts.
 *
 * DESIGN DECISION (see TDD §5.4): Detroit reuses the existing three FocusKind slots
 *   instead of widening the union type:
 *     'zip'    → Detroit ZCTAs (Census TIGER, clipped to city limits)
 *     'police' → DPD precincts (12)
 *     'ward'   → City Council districts (7, effective 2026-01-01) — labelled "Council
 *                districts" via kindLabels, so the user never sees the word "ward".
 *   This keeps focusGeometry.ts (pure, tested, shared with Chicago) untouched.
 *   Neighborhoods (205) as a 4th kind is a deliberate later step: it needs FocusKind
 *   widened, which touches Chicago's code path.
 *
 * DATA: boundaries come from bundled GeoJSON generated by
 *   backend/scripts/export_city_static.py into src/cities/detroit/data/ — loaded lazily
 *   with dynamic import() so Chicago users never download Detroit polygons.
 *
 * STATUS — SKELETON.
 */
import type { BoundaryIndex, FocusKind } from '../../focus/focusGeometry';
import type { AreaOption } from '../../focus/focusAreas';
import type { FocusConfig } from '../CityProfile';
import { notImplemented } from '../CityProfile';

export const DETROIT_KIND_LABELS: Readonly<Record<FocusKind, string>> = {
  zip: 'Zip codes',
  police: 'Police precincts',
  ward: 'Council districts',
};

/**
 * Dynamic-import the generated boundary files and index them with indexBoundaries.
 * O(n) time, O(n) space — n = boundary features (~30 zips + 12 precincts + 7 districts).
 */
export async function loadDetroitBoundaries(): Promise<BoundaryIndex> {
  return notImplemented('loadDetroitBoundaries');
}

/**
 * Option lists for the panel, numeric-aware sorted ("Precinct 2" before "Precinct 10").
 * O(n log n) time, O(n) space — n = boundary features (comparison sort is the floor).
 */
export function detroitAreaOptions(index: BoundaryIndex): Record<FocusKind, readonly AreaOption[]> {
  return notImplemented('detroitAreaOptions', index);
}

export const DETROIT_FOCUS: FocusConfig = {
  loadBoundaries: loadDetroitBoundaries,
  optionsFor: detroitAreaOptions,
  kindLabels: DETROIT_KIND_LABELS,
};
